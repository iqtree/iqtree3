/// Load a lower-triangular rate matrix from a whitespace-separated string
/// It will load the first 190 values into a 20x20 matrix
/// Diagonal and upper-triangular values are set to zero
pub fn load_lower_R(matrix: &str) -> Tensor {
    let vals = matrix
        .split_whitespace()
        .map(|s| s.parse::<f64>().unwrap())
        .collect::<Vec<f64>>();

    let mut data = vec![0.0; 20 * 20];
    let mut index = 0;
    for i in 1..20 {
        for j in 0..i {
            data[i * 20 + j] = vals[index];
            index += 1;
        }
    }
    Tensor::from_vec(data, &[20, 20], &candle_core::Device::Cpu).unwrap()
}

